# frozen_string_literal: true

require 'psych'

module GHB
  # Custom error for configuration validation failures
  class ConfigError < StandardError; end

  # Custom error for failed GitHub REST API calls (carries the response body for diagnosis)
  class GitHubAPIError < StandardError; end

  # Repository settings (branch protection ruleset, required checks) could not be applied.
  class RepositorySettingsError < StandardError; end

  CI_ACTIONS_VERSION = 'v3'
  EXTERNAL_ACTIONS_CONFIG_FILE = 'config/actions.yaml'
  DEFAULT_BUILD_FILE = '.github/workflows/build.yml'
  DEFAULT_GITIGNORE_CONFIG_FILE = 'config/gitignore.yaml'
  DEFAULT_LANGUAGES_CONFIG_FILE = 'config/languages.yaml'
  DEFAULT_LINTERS_CONFIG_FILE = 'config/linters.yaml'
  SERVICES = %i[apt mongodb mysql redis opensearch].freeze
  # Services applied to every detected language, without any dependency-file detection.
  ALWAYS_ENABLED_SERVICES = %i[apt].freeze
  # Enabled when a dependency file mentions the `<service>_dependency` marker from config/languages.yaml.
  DETECTABLE_SERVICES = (SERVICES - ALWAYS_ENABLED_SERVICES).freeze
  SERVICE_DISPLAY_NAMES = { apt: 'APT', mongodb: 'MongoDB', mysql: 'MySQL', opensearch: 'OpenSearch' }.freeze
  DEFAULT_UBUNTU_VERSION = 'ubuntu-latest'
  DEFAULT_MACOS_VERSION = 'macos-latest'
  DEFAULT_JOB_TIMEOUT_MINUTES = 30

  private_constant :CI_ACTIONS_VERSION
  private_constant :EXTERNAL_ACTIONS_CONFIG_FILE
  private_constant :DEFAULT_BUILD_FILE
  private_constant :DEFAULT_GITIGNORE_CONFIG_FILE
  private_constant :DEFAULT_LANGUAGES_CONFIG_FILE
  private_constant :DEFAULT_LINTERS_CONFIG_FILE
  private_constant :SERVICE_DISPLAY_NAMES
  private_constant :DEFAULT_UBUNTU_VERSION
  private_constant :DEFAULT_MACOS_VERSION
  public_constant :DEFAULT_JOB_TIMEOUT_MINUTES
  public_constant :SERVICES
  public_constant :ALWAYS_ENABLED_SERVICES
  public_constant :DETECTABLE_SERVICES

  SECRET_BUNDLES = {
    ssh: { 'ssh-key': '${{secrets.SSH_KEY}}' },
    github_token: { 'github-token': '${{github.token}}' },
    # configure-aws-credentials given both keys and a role signs AssumeRole with the keys, so keys are blanked.
    aws: {
      'aws-access-key-id': "${{vars.AWS_ROLE_TO_ASSUME == '' && secrets.AWS_ACCESS_KEY_ID || ''}}",
      'aws-secret-access-key': "${{vars.AWS_ROLE_TO_ASSUME == '' && secrets.AWS_SECRET_ACCESS_KEY || ''}}",
      'aws-region': '${{secrets.AWS_DEFAULT_REGION}}',
      'aws-role-to-assume': '${{vars.AWS_ROLE_TO_ASSUME}}'
    }
  }.freeze
  private_constant :SECRET_BUNDLES

  LEGACY_AWS_CREDENTIALS = {
    'aws-access-key-id': '${{secrets.AWS_ACCESS_KEY_ID}}',
    'aws-secret-access-key': '${{secrets.AWS_SECRET_ACCESS_KEY}}'
  }.freeze
  public_constant :LEGACY_AWS_CREDENTIALS

  # Rewritten on write: default_with is a no-op once `with:` is set, so stale refs would be copied forward forever.
  RETIRED_SECRETS = { '${{secrets.GH_PAT}}' => '${{github.token}}' }.freeze # rubocop:disable Style/StringHashKeys -- the key is the literal expression matched in generated YAML, not a name
  public_constant :RETIRED_SECRETS

  def self.secrets(*groups)
    SECRET_BUNDLES.fetch_values(*groups).reduce({}, :merge)
  end

  # An unrecognised value is passed through as an explicit runner image.
  RUNNER_FAMILIES = { ubuntu: DEFAULT_UBUNTU_VERSION, macos: DEFAULT_MACOS_VERSION }.freeze
  private_constant :RUNNER_FAMILIES

  def self.runner_image(runs_on)
    return DEFAULT_UBUNTU_VERSION if runs_on.nil?

    RUNNER_FAMILIES[runs_on.to_sym] || runs_on
  end

  def self.vercel?
    return true if File.exist?('vercel.json')

    File.exist?('package.json') && File.read('package.json').match?(/"(?:vercel|next)"/)
  end

  def self.generated_header(source_file)
    "# AUTO-GENERATED by github-build (#{source_file}). Do not edit directly; changes will be overwritten.\n"
  end

  # Default path of a service's options file (overridable with --options-<service>).
  def self.service_config_file(service)
    "config/options/#{service}.yaml"
  end

  # Human readable service name used in CLI help text.
  def self.service_display_name(service)
    SERVICE_DISPLAY_NAMES.fetch(service) { service.to_s.capitalize }
  end

  # Key identifying a service's options file in config validation (and its error messages).
  def self.service_config_key(service)
    :"#{service}_options"
  end

  # Key holding a service's marker string inside a language dependency entry.
  def self.service_dependency_key(service)
    :"#{service}_dependency"
  end

  def self.external_action(name)
    path = File.expand_path("../#{EXTERNAL_ACTIONS_CONFIG_FILE}", __dir__)
    raise(ConfigError, "Missing required external actions file: #{EXTERNAL_ACTIONS_CONFIG_FILE}") unless File.exist?(path)

    actions = Psych.safe_load_file(path)
    validate_external_actions!(actions)
    raise(ConfigError, "External action '#{name}' not found in #{EXTERNAL_ACTIONS_CONFIG_FILE}") unless actions.key?(name)

    "#{name}@#{actions[name]}"
  rescue Psych::SyntaxError => e
    raise(ConfigError, "Invalid YAML in external actions file (#{EXTERNAL_ACTIONS_CONFIG_FILE}): #{e.message}")
  end

  def self.validate_external_actions!(actions)
    return if actions.is_a?(Hash) && !actions.empty? && actions.all? { |name, version| name.is_a?(String) && version.is_a?(String) }

    raise(ConfigError, "#{EXTERNAL_ACTIONS_CONFIG_FILE} must be a non-empty map of action name to version string")
  end
end
